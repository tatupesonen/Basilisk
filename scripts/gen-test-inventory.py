#!/usr/bin/env python3
"""Generate the Ghidra test-parity checklist (docs/inventory/tests/).

Walks a Ghidra source tree and lists every automated test: JUnit classes
(unit, slow/integration, screenshot, processor emulator tests), the C++
decompiler unit tests and the decompiler data tests.

Existing ticks are preserved: a line whose test id is already ticked
(`- [x]`) or marked not applicable (`- [-]`) in the output directory keeps
its mark and any trailing note when the files are regenerated.

Usage: scripts/gen-test-inventory.py [GHIDRA_DIR] [OUT_DIR]
Defaults: ../ghidra and docs/inventory/tests (relative to the repo root).
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GHIDRA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "ghidra"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "docs" / "inventory" / "tests"

# Source-set directory -> (kind label, description)
KINDS = {
    "src/test/java": "unit",
    "src/test.slow/java": "slow",
    "src/test.processors/java": "processor",
    "src/screen/java": "screenshot",
}

# Base classes that mean the test drives the Swing GUI.
GUI_BASES = re.compile(
    r"extends\s+(Abstract(Ghidra)?Headed\w*Test|AbstractDockingTest|AbstractProgramBasedTest"
    r"|AbstractCodeBrowser\w*|AbstractGuiTest|GhidraScreenShotGenerator|AbstractScreenShotGenerator"
    r"|Abstract\w*PluginTest|Abstract\w*ProviderTest|AbstractVisualGraphTest|AbstractGhidraHeadedDebugger\w*"
    r"|AbstractFunctionGraphTest|AbstractDecompilerTest|AbstractMergeTest|Abstract\w*MergeTest"
    r"|AbstractVersionControlActionTest|AbstractVT\w*Test|AbstractEditorTest|Abstract\w*EditorTest)"
)
SWING_HINT = re.compile(r"import\s+(javax\.swing|java\.awt|docking)\b")
TEST_ANNOTATION = re.compile(r"^\s*@Test\b", re.M)
ABSTRACT_CLASS = re.compile(r"\babstract\s+class\b")
LINE = re.compile(r"^- \[(?P<mark>[ x-])\] `(?P<id>[^`]+)`(?P<rest>.*)$")


def module_of(path: Path) -> str:
    """`Ghidra/Features/Base/src/test/...` -> `Features/Base`."""
    parts = path.relative_to(GHIDRA).parts
    if parts[0] == "Ghidra":
        return "/".join(parts[1:3])
    if parts[0] == "GPL":
        return "GPL/" + parts[1]
    return "/".join(parts[:2])


def existing_marks() -> dict[str, tuple[str, str]]:
    marks: dict[str, tuple[str, str]] = {}
    if not OUT.is_dir():
        return marks
    for md in OUT.glob("*.md"):
        for line in md.read_text(encoding="utf-8").splitlines():
            m = LINE.match(line)
            if m and m.group("mark") != " ":
                note = m.group("rest").split(" → ", 1)
                marks[m.group("id")] = (m.group("mark"), note[1] if len(note) > 1 else "")
    return marks


def main() -> None:
    marks = existing_marks()
    OUT.mkdir(parents=True, exist_ok=True)
    modules: dict[str, list[tuple[str, str, int, bool, str]]] = defaultdict(list)

    for java in sorted(GHIDRA.rglob("*.java")):
        rel = java.relative_to(GHIDRA).as_posix()
        kind = next((k for d, k in KINDS.items() if f"/{d}/" in rel), None)
        if kind is None:
            continue
        text = java.read_text(encoding="utf-8", errors="replace")
        tests = len(TEST_ANNOTATION.findall(text))
        is_emulator = kind == "processor" and java.name.endswith("EmulatorTest.java")
        if tests == 0 and not is_emulator:
            continue  # helper, abstract base without tests, or test data
        if ABSTRACT_CLASS.search(text) and tests == 0:
            continue
        gui = bool(GUI_BASES.search(text)) or (kind == "screenshot") or bool(SWING_HINT.search(text))
        cls = rel.split("/java/", 1)[1][: -len(".java")].replace("/", ".")
        modules[module_of(java)].append((cls, kind, tests, gui, rel))

    decomp = GHIDRA / "Ghidra/Features/Decompiler/src/decompile"
    cpp_units: list[tuple[str, int]] = []
    for cc in sorted((decomp / "unittests").glob("*.cc")):
        n = len(re.findall(r"^TEST\(", cc.read_text(encoding="utf-8", errors="replace"), re.M))
        cpp_units.append((cc.name, n))
    datatests = sorted(p.name for p in (decomp / "datatests").glob("*.xml"))

    total_classes = total_tests = gui_classes = 0
    index_rows = []
    for module in sorted(modules):
        rows = modules[module]
        n_tests = sum(r[2] for r in rows)
        n_gui = sum(1 for r in rows if r[3])
        total_classes += len(rows)
        total_tests += n_tests
        gui_classes += n_gui
        slug = module.replace("/", "-").lower()
        done = sum(1 for r in rows if marks.get(r[0], (" ", ""))[0] != " ")
        index_rows.append((module, slug, len(rows), n_tests, n_gui, done))
        lines = [
            f"# Test parity — `{module}`",
            "",
            "Generated by `scripts/gen-test-inventory.py`; ticks and notes after `→` are kept on",
            "regeneration. `- [x]` ported (note names the Rust test), `- [-]` not applicable (note says why).",
            "Kinds: unit, slow (integration), processor (p-code emulator test), screenshot. `GUI` = drives the",
            "Swing UI, so it is ported as an `egui_kittest` test of the equivalent basilisk feature (ADR-006).",
            "",
            f"{len(rows)} test classes, {n_tests} `@Test` methods, {n_gui} GUI classes.",
            "",
        ]
        for cls, kind, tests, gui, rel in rows:
            mark, note = marks.get(cls, (" ", ""))
            tag = f"{kind}, {tests} tests" + (", GUI" if gui else "")
            suffix = f" → {note}" if note else ""
            lines.append(f"- [{mark}] `{cls}` ({tag}){suffix}")
        (OUT / f"{slug}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = [
        "# Test parity — decompiler C++ tests",
        "",
        "Generated by `scripts/gen-test-inventory.py`. Sources under",
        "`Ghidra/Features/Decompiler/src/decompile/` (`unittests/*.cc`, `datatests/*.xml`).",
        "",
        "## C++ unit tests",
        "",
    ]
    for name, n in cpp_units:
        mark, note = marks.get(f"unittests/{name}", (" ", ""))
        lines.append(f"- [{mark}] `unittests/{name}` ({n} tests)" + (f" → {note}" if note else ""))
    lines += ["", "## Decompiler data tests", ""]
    for name in datatests:
        mark, note = marks.get(f"datatests/{name}", (" ", ""))
        lines.append(f"- [{mark}] `datatests/{name}`" + (f" → {note}" if note else ""))
    (OUT / "decompiler-cpp.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    cpp_total = sum(n for _, n in cpp_units)
    idx = [
        "# Ghidra test-parity checklist",
        "",
        "Generated by `scripts/gen-test-inventory.py` from the Ghidra tree at `../ghidra`. Every Ghidra",
        "test gets a Rust counterpart (owner decision, `docs/DIRECTION.md`); one file per Ghidra module.",
        "",
        f"Totals: {total_classes} JUnit test classes with {total_tests} `@Test` methods"
        f" ({gui_classes} classes drive the GUI), {cpp_total} C++ unit tests in {len(cpp_units)} files,"
        f" {len(datatests)} decompiler data tests.",
        "",
        "| Ghidra module | File | Classes | `@Test` | GUI classes | Marked |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for module, slug, n_cls, n_tests, n_gui, done in sorted(index_rows, key=lambda r: -r[3]):
        idx.append(f"| `{module}` | [{slug}.md]({slug}.md) | {n_cls} | {n_tests} | {n_gui} | {done} |")
    idx.append(
        f"| Decompiler C++ | [decompiler-cpp.md](decompiler-cpp.md) | {len(cpp_units)} | {cpp_total}"
        f" + {len(datatests)} data tests | 0 | |"
    )
    (OUT / "README.md").write_text("\n".join(idx) + "\n", encoding="utf-8")
    print(f"{total_classes} classes, {total_tests} @Test, {gui_classes} GUI; {cpp_total} C++ unit, {len(datatests)} datatests")


if __name__ == "__main__":
    main()
